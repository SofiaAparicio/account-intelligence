"""Insight layer: the AI meeting brief for one account.

Design (docs/decisions.md #10, #11)
- No API keys. Briefs for the top accounts were generated by the Claude
  session that built this repo and committed to data/briefs/<account_id>.json,
  each with the exact prompt and context card that produced it.
- get_brief() returns the committed brief if there is one.
- generate_brief() is the optional live path: it calls a local Ollama server
  if OLLAMA_MODEL is set (no key needed). Anything else raises
  NotConfigured, and the UI falls back to showing the prompt with a copy
  button.

Run `python -m src.insights ACC-0001` to print the prompt for an account.
"""

from __future__ import annotations

import json
import os
import sys
from datetime import date
from pathlib import Path

import pandas as pd

from .data import ROOT
from .prompts import BRIEF_PROMPT, BRIEF_SCHEMA, build_context_card

BRIEFS_DIR = ROOT / "data" / "briefs"
BRIEF_KEYS = list(BRIEF_SCHEMA)


class NotConfigured(RuntimeError):
    """No live LLM provider is configured."""


# --------------------------------------------------------------------------
# Prompt assembly
# --------------------------------------------------------------------------
def segment_medians(scored: pd.DataFrame, segment: str) -> dict:
    seg = scored[scored["segment"] == segment]
    return {
        "seat utilisation": f"{seg['seat_utilisation'].median():.0%}",
        "AI feature adoption": f"{seg['ai_usage'].median():.2f}",
        "days since last sales activity": f"{seg['days_since_last_sales_activity'].median():.0f}",
        "open support tickets": f"{seg['nr_support_tickets'].median():.0f}",
        "annual revenue": f"${seg['current_revenue'].median():,.0f}",
    }


def build_prompt(acc: dict, peers: dict | None = None) -> tuple[str, str]:
    """Return (full_prompt, context_card)."""
    card = build_context_card(acc, peers)
    prompt = BRIEF_PROMPT.format(schema=json.dumps(BRIEF_SCHEMA, indent=2), context_card=card)
    return prompt, card


# --------------------------------------------------------------------------
# Committed briefs
# --------------------------------------------------------------------------
def get_brief(account_id: str) -> dict | None:
    path = BRIEFS_DIR / f"{account_id}.json"
    return json.loads(path.read_text()) if path.exists() else None


def list_briefed() -> list[str]:
    return sorted(p.stem for p in BRIEFS_DIR.glob("ACC-*.json"))


def save_brief(account_id: str, brief: dict, prompt: str, context_card: str, generator: str) -> Path:
    validate_brief(brief)
    BRIEFS_DIR.mkdir(parents=True, exist_ok=True)
    path = BRIEFS_DIR / f"{account_id}.json"
    path.write_text(json.dumps({
        "account_id": account_id,
        "generated_on": date.today().isoformat(),
        "generator": generator,
        "brief": brief,
        "context_card": context_card,
        "prompt": prompt,
    }, indent=2, ensure_ascii=False))
    return path


def validate_brief(brief: dict) -> None:
    missing = [k for k in BRIEF_KEYS if k not in brief]
    extra = [k for k in brief if k not in BRIEF_KEYS]
    if missing or extra:
        raise ValueError(f"brief keys mismatch: missing={missing} extra={extra}")
    if len(brief["talking_points"]) != 3:
        raise ValueError("talking_points must have exactly 3 items")
    for k in ("risks", "opportunities", "unknowns"):
        if not isinstance(brief[k], list) or len(brief[k]) > 3:
            raise ValueError(f"{k} must be a list of at most 3 items")


# --------------------------------------------------------------------------
# Optional live generation (no key: local Ollama only)
# --------------------------------------------------------------------------
def generate_brief(acc: dict, peers: dict | None = None, timeout: int = 120) -> dict:
    model = os.getenv("OLLAMA_MODEL")
    if not model:
        raise NotConfigured("Set OLLAMA_MODEL (e.g. 'llama3.1') with Ollama running locally to generate live.")
    import requests  # local import: optional dependency path

    prompt, _ = build_prompt(acc, peers)
    url = os.getenv("OLLAMA_URL", "http://localhost:11434") + "/api/generate"
    r = requests.post(url, json={"model": model, "prompt": prompt, "format": "json", "stream": False},
                      timeout=timeout)
    r.raise_for_status()
    brief = json.loads(r.json()["response"])
    validate_brief(brief)
    return brief


def main() -> None:
    from .data import load_accounts
    from .scoring import score_accounts

    account_id = sys.argv[1] if len(sys.argv) > 1 else "ACC-0001"
    scored = score_accounts(load_accounts()).set_index("account_id")
    acc = scored.loc[account_id].to_dict() | {"account_id": account_id}
    prompt, _ = build_prompt(acc, segment_medians(scored.reset_index(), acc["segment"]))
    print(prompt)


if __name__ == "__main__":
    main()
